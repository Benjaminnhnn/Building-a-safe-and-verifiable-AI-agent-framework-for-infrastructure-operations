"""Evidence domain model with expiry support.

Design notes
------------
* ``expires_at`` is a **required** field.  Every piece of evidence must have a
  finite validity window so that stale data cannot silently influence a Safety
  Gate decision.  The collector is responsible for choosing an appropriate TTL
  (e.g. 5 minutes for a Prometheus scrape, 1 hour for a config snapshot).

* ``is_valid(now)`` returns ``True`` only when *now* is strictly before
  ``expires_at``.  Callers that need to tolerate clock skew should pass
  ``now + skew_tolerance`` rather than relaxing the check here.

* The model is frozen (immutable) after construction.  Any update — including
  extending the expiry — must produce a new Evidence object, preserving the
  full history in the Evidence Store.
"""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Annotated

from pydantic import BaseModel, ConfigDict, Field, model_validator

from evaluation.agent_replay.domain.enums import EvidenceSource


class Evidence(BaseModel):
    """Typed, immutable evidence record with a mandatory expiry timestamp.

    Fields
    ------
    evidence_id : str
        Stable identifier.  Typically a SHA-based ID generated by the
        collector from the canonical evidence content.
    source : EvidenceSource
        Collection mechanism / provenance.
    collected_at : datetime
        When the agent retrieved this evidence.  Must be timezone-aware.
    expires_at : datetime
        Hard validity deadline.  ``is_valid()`` returns ``False`` at or after
        this point.  Must be strictly after ``collected_at``.
    resource_ids : list[str]
        One or more resource IDs that this evidence describes.  Must be
        non-empty; at least one resource must be referenced.
    content_ref : str
        Opaque reference to the raw evidence payload (e.g. a SHA-256 hash
        prefixed with ``"sha256:"``, a Prometheus query string, or a log
        path).  The Evidence Store uses this to verify content integrity.
    summary : str
        Human-readable, one-line description of what the evidence shows.
        Must not contain unredacted credentials or PII.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    evidence_id: str = Field(..., min_length=1)
    source: EvidenceSource
    collected_at: datetime
    expires_at: datetime
    resource_ids: Annotated[list[str], Field(min_length=1)]
    content_ref: str = Field(..., min_length=1)
    summary: str = Field(..., min_length=1)

    # --------------------------------------------------------------------------
    # Validation
    # --------------------------------------------------------------------------

    @model_validator(mode="after")
    def _validate_timestamps(self) -> Evidence:
        if self.collected_at.tzinfo is None or self.collected_at.utcoffset() is None:
            raise ValueError("Evidence.collected_at must be timezone-aware")
        if self.expires_at.tzinfo is None or self.expires_at.utcoffset() is None:
            raise ValueError("Evidence.expires_at must be timezone-aware")
        if self.expires_at <= self.collected_at:
            raise ValueError(
                "Evidence.expires_at must be strictly after collected_at; "
                f"got expires_at={self.expires_at.isoformat()} <= "
                f"collected_at={self.collected_at.isoformat()}"
            )
        if not self.resource_ids:
            raise ValueError("Evidence.resource_ids must contain at least one resource ID")
        for rid in self.resource_ids:
            if not isinstance(rid, str) or not rid.strip():
                raise ValueError("Each resource_id in Evidence.resource_ids must be a non-blank string")
        return self

    # --------------------------------------------------------------------------
    # Business logic
    # --------------------------------------------------------------------------

    def is_valid(self, now: datetime | None = None) -> bool:
        """Return ``True`` if this evidence has not yet expired.

        Parameters
        ----------
        now:
            Reference timestamp.  If ``None``, ``datetime.now(timezone.utc)``
            is used.  Must be timezone-aware when supplied.

        Returns
        -------
        bool
            ``True``  — evidence is current (now < expires_at)
            ``False`` — evidence has expired (now >= expires_at)
        """
        if now is None:
            now = datetime.now(timezone.utc)
        if now.tzinfo is None or now.utcoffset() is None:
            raise ValueError("The 'now' argument must be timezone-aware")
        return now < self.expires_at

